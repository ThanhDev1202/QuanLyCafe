    private void btnThemMonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnThemMonActionPerformed
        if (currentCategoryId == -1) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn Category trước!");
            return;
        }
        try {
            String name = JOptionPane.showInputDialog(this, "Nhập tên món ăn:");
            if (name == null || name.trim().isEmpty()) {
                return;
            }

            String priceinStr = JOptionPane.showInputDialog(this, "Giá nhập:");
            if (priceinStr == null || priceinStr.trim().isEmpty()) {
                return;
            }

            String priceoutStr = JOptionPane.showInputDialog(this, "Giá bán:");
            if (priceoutStr == null || priceoutStr.trim().isEmpty()) {
                return;
            }

            BigDecimal pricein = new BigDecimal(priceinStr.trim());
            BigDecimal priceout = new BigDecimal(priceoutStr.trim());

            Food food = new Food();
            food.setNameFood(name.trim());
            food.setPriceIn(pricein);
            food.setPriceOut(priceout);
            food.setIdcategory(currentCategoryId);

            Request req = new Request("INSERT FOOD", food);
            ClientConnection.getOut().writeObject(req);
            ClientConnection.getOut().flush();

            Response res = (Response) ClientConnection.getIn().readObject();
            JOptionPane.showMessageDialog(this, res.getMessage());
            if ("SUCCESS".equals(res.getStatus())) {
                displayFood(currentCategoryId);
            }
        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Sai định dạng tiền tệ!", "Lỗi nhập liệu", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnThemMonActionPerformed

