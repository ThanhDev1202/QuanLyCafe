    private void btnThemAnhActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnThemAnhActionPerformed
        if (currentCategoryId == -1) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn Category");
            return;
        }
        int row = jTable1.getSelectedRow();
        if (row == -1) {
            JOptionPane.showMessageDialog(this, "Chọn món cần thêm ảnh");
            return;
        }
        try {
            // lấy food id
            int foodId = Integer.parseInt(jTable1.getValueAt(row, 0).toString());
            // file chooser
            JFileChooser jf = new JFileChooser();
            jf.setFileSelectionMode(JFileChooser.FILES_ONLY);
            // filter ảnh
            FileNameExtensionFilter filter = new FileNameExtensionFilter("Image Files", "jpg", "png", "jpeg");
            jf.setFileFilter(filter);
            // mở dialog
            int result = jf.showOpenDialog(this);
            if (result == JFileChooser.APPROVE_OPTION) {
                File file = jf.getSelectedFile();
                // đọc file thành byte[]
                byte[] imageData = Files.readAllBytes(file.toPath());
                // tạo object food
                Food food = new Food();
                food.setId(foodId);
                food.setImageData(imageData);
                // gửi tên file
                food.setImagePath(file.getName());
                // request
                Request req = new Request("UPLOAD IMAGE", food);
                // gửi server
                ClientConnection.getOut().writeObject(req);
                ClientConnection.getOut().flush();
                Response res = (Response) ClientConnection.getIn().readObject();
                if (res.getStatus().equals("SUCCESS")) {
                    JOptionPane.showMessageDialog(this, "Upload ảnh thành công");
                    showFoodImage();
                } else {
                    JOptionPane.showMessageDialog(this, "Upload ảnh thất bại");
                }
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
    }//GEN-LAST:event_btnThemAnhActionPerformed

    public void showFoodImage() {
    int row = jTable1.getSelectedRow();
    if (row == -1) {
        jLabel4.setIcon(null);
        jLabel4.setText("      Không có ảnh");
        return;
    }
    Object cellValue = jTable1.getValueAt(row, 0);
    if (cellValue == null) {
        jLabel4.setIcon(null);
        jLabel4.setText("      Không có ảnh");
        return;
    }

    try {
        int foodId = Integer.parseInt(cellValue.toString());
        Request req = new Request("SHOW IMAGE", foodId);
        ClientConnection.getOut().writeObject(req);
        ClientConnection.getOut().flush();

        Response res = (Response) ClientConnection.getIn().readObject();
        if (res != null && "SUCCESS".equals(res.getStatus())) {
            Food food = (Food) res.getData();
            byte[] imageBytes = food.getImageData();

            if (imageBytes != null && imageBytes.length > 0) {
                ImageIcon icon = new ImageIcon(imageBytes);
                Image img = icon.getImage();
                Image scaled = img.getScaledInstance(jLabel4.getWidth() - 20, jLabel4.getHeight() - 20, Image.SCALE_SMOOTH);
                jLabel4.setIcon(new ImageIcon(scaled));
                jLabel4.setText("");
            } else {
                jLabel4.setIcon(null);
                jLabel4.setText("      Không có ảnh");
            }
        } else {
            jLabel4.setIcon(null);
            jLabel4.setText("      Không có ảnh");
        }
    } catch (Exception e) {
        e.printStackTrace();
    }
}

    public void displayFood(int categoryId) {
    try {
        Request req = new Request("SELECT FOOD BY CATEGORY", categoryId);
        ClientConnection.getOut().writeObject(req);
        ClientConnection.getOut().flush();
        Response res = (Response) ClientConnection.getIn().readObject();
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.setRowCount(0);
        if ("SUCCESS".equals(res.getStatus())) {
            DecimalFormat df = new DecimalFormat("###,###");
            ArrayList<Food> list = (ArrayList<Food>) res.getData();
            for (Food f : list) {
                String priceInFormatted = (f.getPriceIn() != null) ? df.format(f.getPriceIn()) : "0";
                String priceOutFormatted = (f.getPriceOut() != null) ? df.format(f.getPriceOut()) : "0";
                model.addRow(new Object[]{
                    f.getId(),
                    f.getNameFood(),
                    priceInFormatted,
                    priceOutFormatted});
            }
        } else {
            JOptionPane.showMessageDialog(this, res.getMessage());
        }
    } catch (Exception e) {
        e.printStackTrace();
    }
}

public void displayCategory() {
        try {
            Request req = new Request("SELECT CATEGORY", null);
            ClientConnection.getOut().writeObject(req);
            ClientConnection.getOut().flush();

            Response res = (Response) ClientConnection.getIn().readObject();

            if ("SUCCESS".equals(res.getStatus())) {
                ArrayList<CategoryFood> list = (ArrayList<CategoryFood>) res.getData();
                DefaultListModel<String> listModel = new DefaultListModel<>();

                for (CategoryFood c : list) {
                    // 🌟 ĐÃ FIX: Dọn sạch khoảng trắng rác, chỉ để chữ thuần túy để Renderer tự chèn Icon FlatLaf tự động!
                    listModel.addElement("[" + c.getId() + "] - " + c.getTen());
                }
                jList1.setModel(listModel);

                if (!list.isEmpty()) {
                    jList1.setSelectedIndex(0); // Tự động chọn danh mục đầu tiên khi tải xong
                }
            } else if ("NO CATEGORY".equals(res.getStatus())) {
                JOptionPane.showMessageDialog(this, "Hệ thống chưa dữ liệu loại danh mục nào!");
            } else {
                JOptionPane.showMessageDialog(this, res.getMessage());
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
    }
