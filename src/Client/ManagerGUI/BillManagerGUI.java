    private void jButton5ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton5ActionPerformed
        try {
            Request req = new Request("GET FOOD FREQ", null);
            Response res = (Response) ClientConnection.sendRequest(req);

            if (res == null || !"SUCCESS".equals(res.getStatus())) {
                JOptionPane.showMessageDialog(this, "Không lấy được dữ liệu");
                return;
            }

            List<BillInfor> list = (List<BillInfor>) res.getData();

            Map<String, Integer> map = new HashMap<>();

            for (BillInfor b : list) {
                map.put(
                        b.getFoodName(),
                        map.getOrDefault(b.getFoodName(), 0) + b.getQuantity()
                );
            }

            showFoodBarChart(map);

        } catch (Exception e) {
            e.printStackTrace();
        }
    }//GEN-LAST:event_jButton5ActionPerformed
    private void showRevenueChart() {
        if (bills == null || bills.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Không có dữ liệu");
            return;
        }
        Map<String, BigDecimal> revenueByDate = new TreeMap<>();

        SimpleDateFormat sdf
                = new SimpleDateFormat("dd/MM/yyyy");

        for (Bill bill : bills) {

            if (bill.getStatus() != Bill.PAID
                    || bill.getDateCheckOut() == null) {
                continue;
            }
            String date = sdf.format(bill.getDateCheckOut());
            revenueByDate.put(
                    date,
                    revenueByDate.getOrDefault(
                            date,
                            BigDecimal.ZERO)
                            .add(bill.getTotalPrice())
            );
        }
        DefaultCategoryDataset dataset
                = new DefaultCategoryDataset();
        for (Map.Entry<String, BigDecimal> entry
                : revenueByDate.entrySet()) {
            dataset.addValue(
                    entry.getValue(),
                    "Doanh thu",
                    entry.getKey()
            );
        }
        JFreeChart chart
                = ChartFactory.createLineChart(
                        "Doanh thu theo ngày",
                        "Ngày",
                        "VNĐ",
                        dataset
                );
        ChartPanel panel
                = new ChartPanel(chart);
        JFrame frame
                = new JFrame("Biểu đồ doanh thu");
        frame.setDefaultCloseOperation(
                JFrame.DISPOSE_ON_CLOSE);
        frame.add(panel);
        frame.setSize(1800, 1000);
        frame.setLocationRelativeTo(null);
        frame.setVisible(true);
        CategoryPlot plot = chart.getCategoryPlot();

        LineAndShapeRenderer renderer
                = (LineAndShapeRenderer) plot.getRenderer();

        renderer.setDefaultShapesVisible(true);
        renderer.setDefaultShapesFilled(true);

        renderer.setDefaultItemLabelsVisible(true);
        renderer.setDefaultItemLabelGenerator(
                new StandardCategoryItemLabelGenerator());
    }

    private void showFoodBarChart(Map<String, Integer> data) {

        DefaultCategoryDataset dataset = new DefaultCategoryDataset();

        for (Map.Entry<String, Integer> e : data.entrySet()) {
            dataset.addValue(e.getValue(), "Số lượng bán", e.getKey());
        }

        JFreeChart barChart = ChartFactory.createBarChart(
                "Top sản phẩm bán chạy",
                "Món ăn",
                "Số lượng",
                dataset
        );

        ChartPanel panel = new ChartPanel(barChart);

        JFrame frame = new JFrame("Thống kê sản phẩm bán chạy");
        frame.setDefaultCloseOperation(JFrame.DISPOSE_ON_CLOSE);
        frame.add(panel);
        frame.setSize(900, 600);
        frame.setLocationRelativeTo(null);
        frame.setVisible(true);
    }

    private void loadData() {
        try {
            Request req = new Request("GET ALL BILLS", null);
            Response res = (Response) ClientConnection.sendRequest(req);
            if (res != null && "SUCCESS".equals(res.getStatus())) {
                bills = (List<Bill>) res.getData();
                loadBill(bills);
            } else {
                JOptionPane.showMessageDialog(this, "Không tải được danh sách hóa đơn");
            }
        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Lỗi kết nối server");
        }
    }

    public void loadBill(List<Bill> bills) {

        DefaultTableModel model
                = (DefaultTableModel) jTable1.getModel();

        model.setRowCount(0);

        BigDecimal revenue = BigDecimal.ZERO;

        for (Bill bill : bills) {
            model.addRow(new Object[]{
                bill.getId(),
                bill.getDateCheckIn(),
                bill.getDateCheckOut(),
                bill.getDiscount(),
                bill.getTotalPrice(),
                bill.getStatus() == 0
                ? "Chưa thanh toán"
                : "Đã thanh toán",
                bill.getTableID()
            });

            if (bill.getStatus() == 1) {
                revenue = revenue.add(bill.getTotalPrice());
            }
        }
        DecimalFormat df = new DecimalFormat("#,###");
        jLabel2.setText(df.format(revenue) + " VNĐ");
    }

    private void filterByDate(java.util.Date selectedDate) {

        SimpleDateFormat sdf = new SimpleDateFormat("dd/MM/yyyy");
        String target = sdf.format(selectedDate);

        List<Bill> filtered = new java.util.ArrayList<>();

        for (Bill b : bills) {
            if (b.getDateCheckOut() == null) {
                continue;
            }

            if (target.equals(sdf.format(b.getDateCheckOut()))) {
                filtered.add(b);
            }
        }

        loadBill(filtered);
    }
    
