    private void showQrPayment(List<BillInfor> details,
            java.math.BigDecimal totalAmount) {
        new Thread(() -> {
            try {

                String qrUrl
                        = "https://img.vietqr.io/image/TCB-6042088888-compact2.png"
                        + "?amount=" + totalAmount.toPlainString()
                        + "&addInfo=ORDER_PAYMENT";

                BufferedImage qrImage
                        = ImageIO.read(new URL(qrUrl));

                Image scaled
                        = qrImage.getScaledInstance(
                                400,
                                500,
                                Image.SCALE_SMOOTH);

                ImageIcon icon
                        = new ImageIcon(scaled);

                SwingUtilities.invokeLater(() -> {

                    JPanel panel
                            = new JPanel(
                                    new GridLayout(1, 2, 10, 10));

                    // ======================
                    // BÊN TRÁI: HÓA ĐƠN
                    // ======================
                    JTextArea txtBill
                            = new JTextArea();

                    txtBill.setEditable(false);

                    txtBill.setFont(
                            new java.awt.Font(
                                    "Monospaced",
                                    java.awt.Font.PLAIN,
                                    14));

                    txtBill.append("CHI TIẾT ĐƠN HÀNG\n\n");

                    for (BillInfor item : details) {

                        java.math.BigDecimal lineTotal
                                = item.getPrice().multiply(
                                        new java.math.BigDecimal(
                                                item.getQuantity()));

                        txtBill.append(
String.format(
    "%-15s %10s x%-3d %12s\n",
    item.getFoodName(),
    df.format(item.getPrice()),
    item.getQuantity(),
    df.format(lineTotal)
));
                    }
                    txtBill.append(
                            "\n------------------------------\n");
txtBill.append(
        "Tổng tiền: "
        + df.format(totalAmount)
        + " VND"
);

                    JScrollPane billScroll
                            = new JScrollPane(txtBill);

                    JPanel leftPanel
                            = new JPanel(
                                    new BorderLayout());

                    leftPanel.add(
                            billScroll,
                            BorderLayout.CENTER);

                    // ======================
                    // BÊN PHẢI: QR
                    // ======================
                    JLabel qrLabel
                            = new JLabel(icon);

                    qrLabel.setHorizontalAlignment(
                            SwingConstants.CENTER);

                    JPanel rightPanel
                            = new JPanel(
                                    new BorderLayout());

                    rightPanel.add(
                            qrLabel,
                            BorderLayout.CENTER);

                    panel.add(leftPanel);
                    panel.add(rightPanel);

                    int result = JOptionPane.showConfirmDialog(
                            OrderGUI2.this,
                            panel,
                            "Thanh toán QR",
                            JOptionPane.YES_NO_OPTION,
                            JOptionPane.PLAIN_MESSAGE
                    );

                    if (result == JOptionPane.YES_OPTION) {
                        handlePaymentSuccess();
                    } else {
                        JOptionPane.showMessageDialog(this, "Đã hủy thanh toán!");
                    }

                });

            } catch (Exception ex) {
                ex.printStackTrace();

                SwingUtilities.invokeLater(()
                        -> JOptionPane.showMessageDialog(
                                OrderGUI2.this,
                                "Không thể tạo QR!",
                                "Lỗi",
                                JOptionPane.ERROR_MESSAGE));
            }
        }).start();
    }
    private void handlePaymentSuccess() {

        try {
            Object[] data = {
                pendingOrder,
                pendingTotal
            };

            Request req = new Request(
                    "CREATE ORDER WITH NO TABLE",
                    data
            );
            Response res = (Response) ClientConnection.sendRequest(req);
            if (res == null || !"SUCCESS".equals(res.getStatus())) {
                JOptionPane.showMessageDialog(this, "Thanh toán thất bại!");
                return;
            }
            int billId = ((Number) res.getData()).intValue();
            Bill bill = new Bill();
            bill.setId(billId);
            bill.setTotalPrice(pendingTotal);

            shared.PrintInvoice.saveInvoice(bill, pendingOrder);

            JOptionPane.showMessageDialog(this, "Thanh toán thành công!");

            tempOrderList.clear();
            pendingOrder.clear();
            pendingTotal = BigDecimal.ZERO;

            updateTable(new ArrayList<>());
            if (listener != null) {
                listener.onOrderPlacedSuccessfully();
            }

        } catch (Exception ex) {
            ex.printStackTrace();
            JOptionPane.showMessageDialog(this, ex.getMessage());
        }
    }
